local fx = require("tests.fixture")

describe("browser", function()
  it("opens at the root with the changed folders and files", function()
    fx.review()
    local text = table.concat(fx.shown(), "\n")
    expect(text).contains("src/")
    expect(text:find("README", 1, true) == nil).truthy("unchanged file hidden")
    expect(text:find("package-lock", 1, true) == nil).truthy("generated file hidden")
  end)

  it("enters a folder and shows statuses, deletions and renames", function()
    fx.cursor_on("src/")
    fx.press("<CR>")
    local text = table.concat(fx.shown(), "\n")
    expect(text).contains("M app.ts")
    expect(text).contains("A new.ts")
    expect(text).contains("D old.ts")
    expect(text).contains("R renamed.ts")
    expect(text).contains("← src/name.ts")
  end)

  it("saves a read mark with :w", function()
    fx.cursor_on("app.ts")
    fx.tick("x")
    expect(vim.bo.modified).truthy("modified before :w")
    vim.cmd("write")
    expect(require("reviewer.core").is_read("src/app.ts")).truthy("app.ts read")
    expect(vim.bo.modified).falsy("saved")
  end)

  it("marks a whole folder", function()
    fx.press("-")
    fx.cursor_on("src/")
    fx.tick("x")
    vim.cmd("write")
    local core = require("reviewer.core")
    for _, p in ipairs({ "src/app.ts", "src/new.ts", "src/old.ts", "src/renamed.ts" }) do
      expect(core.is_read(p)).truthy(p)
    end
    fx.cursor_on("src/")
    fx.tick(" ")
    vim.cmd("write")
    expect(core.is_read("src/new.ts")).falsy("unmarked again")
  end)

  it("ignores edits that are not a checkbox", function()
    vim.api.nvim_buf_set_lines(0, 0, 0, false, { "some text" })
    vim.cmd("write")
    expect(table.concat(fx.shown(), "\n"):find("some text", 1, true) == nil).truthy("edit dropped")
  end)

  it("opens a file in the same window, then - comes back to its folder", function()
    vim.cmd("Review browse src")
    fx.cursor_on("app.ts")
    fx.press("<CR>")
    expect(vim.api.nvim_buf_get_name(0)).contains("src/app.ts")
    expect(#vim.api.nvim_tabpage_list_wins(0)).equal(1, "windows")
    fx.press("-")
    expect(vim.api.nvim_buf_get_name(0)).contains("reviewer://")
    expect(vim.api.nvim_get_current_line()).contains("app.ts")
  end)
end)
